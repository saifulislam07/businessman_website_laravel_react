#!/usr/bin/env bash
# Regenerates the nginx real-IP snippet from Cloudflare's published ranges and reloads nginx.
# Run as root (or via sudo) now and then, e.g. from a monthly cron job.
set -euo pipefail

OUT=/etc/nginx/snippets/cloudflare-realip.conf
TMP=$(mktemp)

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%F). Do not edit by hand."
  for url in https://www.cloudflare.com/ips-v4 https://www.cloudflare.com/ips-v6; do
    curl -fsS "$url" | while read -r ip; do
      [ -n "$ip" ] && echo "set_real_ip_from $ip;"
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

# Refuse to install an obviously broken download.
[ "$(grep -c '^set_real_ip_from' "$TMP")" -ge 10 ] || { echo "Too few ranges downloaded; keeping the old file." >&2; exit 1; }

install -m 644 "$TMP" "$OUT"
rm -f "$TMP"
nginx -t
systemctl reload nginx
echo "Updated $OUT"
